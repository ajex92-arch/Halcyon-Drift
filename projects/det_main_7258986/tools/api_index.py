"""Builds docs/API_INDEX.md: every script's public signals and functions.

WHAT THIS IS: a quick "phone book" of the game code. For each script in
scripts/ it lists the signals and the functions other files may call
(names starting with "_" are private, so they are left out).

HOW TO RUN IT (from the remake folder, after bigger code changes):
    python tools/api_index.py
It only reads the .gd files and rewrites docs/API_INDEX.md. It needs
nothing but Python itself.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "API_INDEX.md")

CLASS_RE = re.compile(r"^class_name\s+(\w+)")
EXTENDS_RE = re.compile(r"^extends\s+(\w+)")
SIGNAL_RE = re.compile(r"^signal\s+\w+")
FUNC_RE = re.compile(r"^(static\s+)?func\s+([A-Za-z]\w*)\s*\(")


def entries(path):
    """The class line and the public signals and functions of one script."""
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    cls, ext, found = "", "", []
    i = 0
    while i < len(lines):
        ln = lines[i]
        if CLASS_RE.match(ln):
            cls = CLASS_RE.match(ln).group(1)
        elif EXTENDS_RE.match(ln) and not ext:
            ext = EXTENDS_RE.match(ln).group(1)
        elif SIGNAL_RE.match(ln):
            found.append(ln.strip())
        elif FUNC_RE.match(ln):
            # A signature may run over several lines: join them up to the ":".
            sig = ln.strip()
            while not sig.endswith(":") and i + 1 < len(lines):
                i += 1
                sig += " " + lines[i].strip()
            found.append(sig[:-1].strip() if sig.endswith(":") else sig)
        i += 1
    return cls, ext, found


def main():
    paths = []
    for dirpath, _dirs, files in os.walk(os.path.join(ROOT, "scripts")):
        for name in files:
            if name.endswith(".gd"):
                full = os.path.join(dirpath, name)
                paths.append(os.path.relpath(full, ROOT).replace("\\", "/"))
    out = [
        "# API index (generated by tools/api_index.py; the code is the contract)",
        "",
        "Public signals and functions per script. Names starting with \"_\" are",
        "private and left out, and so are scripts with nothing public. Rebuild it",
        "with `python tools/api_index.py` (from the remake folder) after bigger",
        "changes.",
    ]
    for rel in sorted(paths):
        cls, ext, found = entries(os.path.join(ROOT, rel))
        if not found:
            continue
        kind = f"class_name {cls} extends {ext}" if cls else f"extends {ext}"
        out.append("")
        out.append(f"## {rel}  ({kind})")
        out.extend(f"- `{e}`" for e in found)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {OUT} ({len(out)} lines)")


if __name__ == "__main__":
    main()
